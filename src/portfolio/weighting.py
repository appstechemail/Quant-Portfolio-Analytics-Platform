# ============================================================
# GROSS EXPOSURE TARGETING
# ============================================================

def target_gross_exposure(
    weights: pd.Series,
    target_gross: float,
) -> pd.Series:
    """
    Scale portfolio
    to desired gross exposure.
    """

    gross = float(
        np.abs(weights).sum()
    )

    if gross < EPS:

        return weights.copy()

    scale = (
        target_gross
        / gross
    )

    return weights * scale


# ============================================================
# NET EXPOSURE TARGETING
# ============================================================

def target_net_exposure(
    weights: pd.Series,
    target_net: float,
) -> pd.Series:
    """
    Adjust portfolio
    toward desired net exposure.
    """

    current_net = float(
        weights.sum()
    )

    adjustment = (
        target_net
        - current_net
    )

    n = len(weights)

    if n == 0:

        return weights

    return (
        weights
        + adjustment / n
    )


# ============================================================
# LONG SHORT NORMALIZATION
# ============================================================

def normalize_long_short_books(
    weights: pd.Series,
    target_gross: float,
    target_net: float,
) -> pd.Series:
    """
    Institutional long-short scaling.
    """

    weights = (
        target_gross_exposure(
            weights,
            target_gross,
        )
    )

    weights = (
        target_net_exposure(
            weights,
            target_net,
        )
    )

    return weights


# ============================================================
# LONG BOOK EXPOSURE
# ============================================================

def long_exposure(
    weights: pd.Series,
) -> float:

    return float(
        weights[
            weights > 0
        ].sum()
    )


# ============================================================
# SHORT BOOK EXPOSURE
# ============================================================

def short_exposure(
    weights: pd.Series,
) -> float:

    return float(
        np.abs(
            weights[
                weights < 0
            ]
        ).sum()
    )


# ============================================================
# GROSS EXPOSURE
# ============================================================

def gross_exposure(
    weights: pd.Series,
) -> float:

    return float(
        np.abs(weights).sum()
    )


# ============================================================
# NET EXPOSURE
# ============================================================

def net_exposure(
    weights: pd.Series,
) -> float:

    return float(
        weights.sum()
    )


