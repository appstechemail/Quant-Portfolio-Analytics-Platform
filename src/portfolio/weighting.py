def validate_selected_portfolio(
    df: pd.DataFrame,
    config: PortfolioSelectionConfig,
) -> None:
    """
    Validate portfolio input.
    """

    required = [

        "Date",

        config.selected_column,

        config.score_column,
    ]

    missing = [
        col
        for col in required
        if col not in df.columns
    ]

    if missing:

        raise ValueError(
            f"Missing required columns: {missing}"
        )

    if df.empty:

        raise ValueError(
            "Portfolio dataframe is empty."
        )

    selected_count = int(
        df[config.selected_column].sum()
    )

    if selected_count == 0:

        raise ValueError(
            "No securities selected."
        )


