# ============================================================
# FACTORY
# ============================================================

class WeightEngineFactory:

    @staticmethod
    def create(
        method: WeightMethod,
        config: PortfolioSelectionConfig,
    ) -> BaseWeightEngine:

        if method == WeightMethod.EQUAL:
            return EqualWeightEngine(
                config
            )

        if method == WeightMethod.SCORE:
            return ScoreWeightEngine(
                config
            )

        if method == WeightMethod.SOFTMAX:
            return SoftmaxWeightEngine(
                config
            )

        if (
            method
            == WeightMethod.INVERSE_VOLATILITY
        ):
            return (
                InverseVolatilityEngine(
                    config
                )
            )

        if method == WeightMethod.KELLY:
            return KellyWeightEngine(
                config
            )

        if (
            method
            == WeightMethod.RISK_PARITY
        ):
            return RiskParityEngine(
                config
            )

        if (
            hasattr(
                WeightMethod,
                "MAX_SHARPE"
            )
            and method
            == WeightMethod.MAX_SHARPE
        ):
            return MaxSharpeEngine(
                config
            )

        if (
            hasattr(
                WeightMethod,
                "MIN_VARIANCE"
            )
            and method
            == WeightMethod.MIN_VARIANCE
        ):
            return MinVarianceEngine(
                config
            )

        if (
            hasattr(
                WeightMethod,
                "HRP"
            )
            and method
            == WeightMethod.HRP
        ):
            return HRPEngine(
                config
            )

        if (
            hasattr(
                WeightMethod,
                "ERC"
            )
            and method
            == WeightMethod.ERC
        ):
            return ERCEngine(
                config
            )

        raise ValueError(
            f"Unknown weighting method: {method}"
        )


