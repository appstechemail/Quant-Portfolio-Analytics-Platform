# ============================================================
# LONG ONLY CONSTRUCTION
# ============================================================

def construct_long_only_weights(
    group: pd.DataFrame,
    engine: BaseWeightEngine,
) -> pd.Series:
    """
    Build long-only portfolio.
    """

    raw_weights = (
        engine.compute_weights(
            group
        )
    )

    weights = (
        engine.apply_constraints(
            raw_weights
        )
    )

    return weights


# ============================================================
# LONG SHORT CONSTRUCTION
# ============================================================

def construct_long_short_weights(
    group: pd.DataFrame,
    engine: BaseWeightEngine,
    config: PortfolioSelectionConfig,
) -> pd.Series:
    """
    Construct long-short portfolio.
    """

    longs = group.loc[
        group[
            DEFAULT_SIDE_COLUMN
        ]
        == LONG
    ]

    shorts = group.loc[
        group[
            DEFAULT_SIDE_COLUMN
        ]
        == SHORT
    ]

    long_weights = pd.Series(
        0.0,
        index=group.index,
    )

    short_weights = pd.Series(
        0.0,
        index=group.index,
    )

    # ---------------------------------
    # Long book
    # ---------------------------------

    if not longs.empty:

        lw = engine.compute_weights(
            longs
        )

        lw = normalize_weights(
            lw
        )

        long_weights.loc[
            longs.index
        ] = lw

    # ---------------------------------
    # Short book
    # ---------------------------------

    if not shorts.empty:

        sw = engine.compute_weights(
            shorts
        )

        sw = normalize_weights(
            sw
        )

        short_weights.loc[
            shorts.index
        ] = -sw

    weights = (
        long_weights
        + short_weights
    )

    return weights


# ============================================================
# DATE LEVEL CONSTRUCTION
# ============================================================

def construct_weights_for_date(
    group: pd.DataFrame,
    config: PortfolioSelectionConfig,
) -> pd.Series:
    """
    Construct weights
    for a single rebalance date.
    """

    engine = (
        WeightEngineFactory.create(
            config.weight_method,
            config,
        )
    )

    if (
        config.selection_method
        == SelectionMethod.LONG_ONLY
    ):

        weights = (
            construct_long_only_weights(
                group,
                engine,
            )
        )

    else:

        weights = (
            construct_long_short_weights(
                group,
                engine,
                config,
            )
        )

    weights = apply_exposure_targets(
        weights,
        config,
    )

    return weights


# ============================================================
# PORTFOLIO CONSTRUCTION
# ============================================================

def compute_portfolio_weights(
    portfolio_df: pd.DataFrame,
    config: PortfolioSelectionConfig,
) -> WeightResult:
    """
    Main weighting API.
    """

    validate_selected_portfolio(
        portfolio_df,
        config,
    )

    out = (
        portfolio_df.copy()
    )

    out[
        config.weight_column
    ] = 0.0

    selected = out.loc[
        out[
            config.selected_column
        ]
    ].copy()

    if selected.empty:

        diagnostics = (
            WeightDiagnostics()
        )

        return WeightResult(
            weighted_df=out,
            diagnostics=diagnostics,
        )

    # ---------------------------------
    # Rebalance Date Loop
    # ---------------------------------

    for (
        date,
        group,
    ) in selected.groupby(
        "Date"
    ):

        weights = (
            construct_weights_for_date(
                group,
                config,
            )
        )

        out.loc[
            group.index,
            config.weight_column,
        ] = (
            weights.values
        )

    # ---------------------------------
    # Portfolio Diagnostics
    # ---------------------------------

    final_weights = (
        out[
            config.weight_column
        ]
    )

    diagnostics = (
        WeightDiagnostics(
            gross_exposure=float(
                np.abs(
                    final_weights
                ).sum()
            ),
            net_exposure=float(
                final_weights.sum()
            ),
            max_weight=float(
                final_weights.max()
            ),
            min_weight=float(
                final_weights.min()
            ),
            effective_n=
            effective_number_of_positions(
                final_weights
            ),
            concentration_hhi=
            concentration_hhi(
                final_weights
            ),
        )
    )

    return WeightResult(
        weighted_df=out,
        diagnostics=diagnostics,
    )

