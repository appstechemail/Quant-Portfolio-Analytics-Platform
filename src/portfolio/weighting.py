# ============================================================
# EQUAL WEIGHT ENGINE
# ============================================================

class EqualWeightEngine(
    BaseWeightEngine
):

    def compute_weights(
        self,
        group: pd.DataFrame,
    ) -> pd.Series:

        n = len(group)

        if n == 0:

            return pd.Series(
                dtype=float,
                index=group.index,
            )

        return pd.Series(
            1.0 / n,
            index=group.index,
        )


# ============================================================
# SCORE WEIGHT ENGINE
# ============================================================

class ScoreWeightEngine(
    BaseWeightEngine
):

    def compute_weights(
        self,
        group: pd.DataFrame,
    ) -> pd.Series:

        scores = (
            group[
                self.config.score_column
            ]
            .fillna(0.0)
            .clip(lower=0.0)
        )

        return normalize_weights(
            scores
        )


# ============================================================
# SOFTMAX ENGINE
# ============================================================

class SoftmaxWeightEngine(
    BaseWeightEngine
):

    def __init__(
        self,
        config: PortfolioSelectionConfig,
    ) -> None:

        super().__init__(config)

        self.temperature = getattr(
            config,
            "softmax_temperature",
            1.0,
        )

    def compute_weights(
        self,
        group: pd.DataFrame,
    ) -> pd.Series:

        scores = (
            group[
                self.config.score_column
            ]
            .fillna(0.0)
        )

        scores = (
            scores
            - scores.max()
        )

        exp_scores = np.exp(
            scores
            / max(
                self.temperature,
                EPS,
            )
        )

        return normalize_weights(
            pd.Series(
                exp_scores,
                index=group.index,
            )
        )


# ============================================================
# INVERSE VOLATILITY ENGINE
# ============================================================

class InverseVolatilityEngine(
    BaseWeightEngine
):

    def __init__(
        self,
        config: PortfolioSelectionConfig,
        volatility_column: str = (
            "Volatility"
        ),
    ) -> None:

        super().__init__(config)

        self.volatility_column = (
            volatility_column
        )

    def compute_weights(
        self,
        group: pd.DataFrame,
    ) -> pd.Series:

        if (
            self.volatility_column
            not in group.columns
        ):

            return EqualWeightEngine(
                self.config
            ).compute_weights(
                group
            )

        vol = (
            group[
                self.volatility_column
            ]
            .replace(
                0,
                np.nan,
            )
            .fillna(
                group[
                    self.volatility_column
                ].median()
            )
            .clip(
                lower=EPS
            )
        )

        inv_vol = 1.0 / vol

        return normalize_weights(
            inv_vol
        )


