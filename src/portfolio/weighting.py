# FULL PORTFOLIO DIAGNOSTICS
# ============================================================

def portfolio_diagnostics(
    portfolio_df: pd.DataFrame,
    config: PortfolioSelectionConfig,
) -> dict:
    """
    Portfolio-wide diagnostics.
    """

    weights = (
        portfolio_df[
            config.weight_column
        ]
        .fillna(0.0)
    )

    diagnostics = {

        # exposures
        **exposure_summary(
            weights
        ),

        # counts
        "positions":
            position_count(
                weights
            ),

        "long_positions":
            long_position_count(
                weights
            ),

        "short_positions":
            short_position_count(
                weights
            ),

        # diversification
        "effective_n":
            effective_number_of_positions(
                weights
            ),

        "diversification_score":
            diversification_score(
                weights
            ),

        "concentration_hhi":
            concentration_hhi(
                weights
            ),

        "top5_concentration":
            concentration_ratio(
                weights,
                5,
            ),

        "top10_concentration":
            concentration_ratio(
                weights,
                10,
            ),
    }

    diagnostics.update(
        weight_distribution(
            weights
        )
    )

    return diagnostics

