def normalize_weights(
    weights: pd.Series,
) -> pd.Series:
    """
    Normalize weights to sum to 1.
    """

    total = float(weights.sum())

    if abs(total) < EPS:

        return pd.Series(
            0.0,
            index=weights.index,
        )

    return weights / total


def normalize_long_short(
    weights: pd.Series,
    gross_target: float = 1.0,
) -> pd.Series:
    """
    Normalize by gross exposure.
    """

    gross = float(
        np.abs(weights).sum()
    )

    if gross < EPS:

        return pd.Series(
            0.0,
            index=weights.index,
        )

    return (
        weights
        / gross
        * gross_target
    )


def effective_number_of_positions(
    weights: pd.Series,
) -> float:
    """
    Effective N.

    1 / sum(w^2)
    """

    w = weights.fillna(0.0)

    denom = float(
        (w ** 2).sum()
    )

    if denom < EPS:

        return 0.0

    return 1.0 / denom


def concentration_hhi(
    weights: pd.Series,
) -> float:
    """
    Herfindahl-Hirschman Index.
    """

    w = weights.fillna(0.0)

    return float(
        (w ** 2).sum()
    )


def apply_weight_caps(
    weights: pd.Series,
    min_weight: float,
    max_weight: float,
) -> pd.Series:
    """
    Apply weight bounds.

    Re-normalization handled elsewhere.
    """

    return weights.clip(
        lower=min_weight,
        upper=max_weight,
    )


# ============================================================
# BASE ENGINE
# ============================================================

class BaseWeightEngine(ABC):
    """
    Abstract weighting engine.
    """

    def __init__(
        self,
        config: PortfolioSelectionConfig,
    ) -> None:

        self.config = config

    @abstractmethod
    def compute_weights(
        self,
        group: pd.DataFrame,
    ) -> pd.Series:
        """
        Compute raw weights.
        """

        raise NotImplementedError

    def apply_constraints(
        self,
        weights: pd.Series,
    ) -> pd.Series:
        """
        Apply portfolio constraints.
        """

        weights = apply_weight_caps(
            weights,
            self.config.min_weight,
            self.config.max_weight,
        )

        return normalize_weights(
            weights
        )

    def build_diagnostics(
        self,
        weights: pd.Series,
    ) -> WeightDiagnostics:
        """
        Build diagnostics object.
        """

        return WeightDiagnostics(

            gross_exposure=float(
                np.abs(weights).sum()
            ),

            net_exposure=float(
                weights.sum()
            ),

            max_weight=float(
                weights.max()
            ),

            min_weight=float(
                weights.min()
            ),

            effective_n=
                effective_number_of_positions(
                    weights
                ),

            concentration_hhi=
                concentration_hhi(
                    weights
                ),
        )


