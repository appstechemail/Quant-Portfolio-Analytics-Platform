def investable_capital_fraction(
    config: PortfolioSelectionConfig,
) -> float:
    """
    Capital available for positions.
    """

    return (
        1.0
        - config.cash_buffer
    )


# ============================================================
# SCALE PORTFOLIO TO CASH BUFFER
# ============================================================

def apply_cash_buffer(
    weights: pd.Series,
    config: PortfolioSelectionConfig,
) -> pd.Series:
    """
    Reserve cash from portfolio.
    """

    investable = (
        investable_capital_fraction(
            config
        )
    )

    return (
        weights
        * investable
    )


# ============================================================
# ADD CASH ROW
# ============================================================

def append_cash_position(
    portfolio_df: pd.DataFrame,
    config: PortfolioSelectionConfig,
) -> pd.DataFrame:
    """
    Optional synthetic cash position.
    """

    cash_weight = (
        compute_cash_weight(
            config
        )
    )

    if cash_weight <= 0:

        return portfolio_df

    rows = []

    for date in (
        portfolio_df["Date"]
        .drop_duplicates()
    ):

        rows.append({

            "Date": date,

            "Ticker": "CASH",

            config.weight_column:
                cash_weight,

            DEFAULT_CASH_COLUMN:
                cash_weight,

            DEFAULT_SIDE_COLUMN:
                NEUTRAL,
        })

    cash_df = pd.DataFrame(
        rows
    )

    return pd.concat(
        [
            portfolio_df,
            cash_df,
        ],
        ignore_index=True,
    )


# ============================================================
# REMOVE TINY POSITIONS
# ============================================================

def remove_small_positions(
    weights: pd.Series,
    threshold: float,
) -> pd.Series:
    """
    Eliminate tiny positions.
    """

    cleaned = weights.copy()

    cleaned[
        np.abs(cleaned)
        < threshold
    ] = 0.0

    return cleaned


# ============================================================
# REDISTRIBUTE REMAINING CAPITAL
# ============================================================

def redistribute_after_pruning(
    weights: pd.Series,
) -> pd.Series:
    """
    Re-normalize after removing
    tiny positions.
    """

    gross = float(
        np.abs(weights).sum()
    )

    if gross < EPS:

        return weights

    return (
        weights
        / gross
    )


# ============================================================
# FULL CASH PROCESSING
# ============================================================

def apply_cash_management(
    weights: pd.Series,
    config: PortfolioSelectionConfig,
) -> pd.Series:
    """
    Institutional cash workflow.
    """

    weights = (
        remove_small_positions(
            weights,
            config.min_trade_weight,
        )
    )

    weights = (
        redistribute_after_pruning(
            weights
        )
    )

    weights = (
        apply_cash_buffer(
            weights,
            config,
        )
    )

    return weights


