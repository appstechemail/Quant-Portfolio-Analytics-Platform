# ============================================================
# APPLY TARGETS
# ============================================================

def apply_exposure_targets(
    weights: pd.Series,
    config: PortfolioSelectionConfig,
) -> pd.Series:
    """
    Master exposure targeting.
    """

    if (
        config.selection_method
        == SelectionMethod.LONG_ONLY
    ):

        return target_gross_exposure(
            weights,
            config.gross_exposure_target,
        )

    return normalize_long_short_books(
        weights,
        config.gross_exposure_target,
        config.net_exposure_target,
    )

